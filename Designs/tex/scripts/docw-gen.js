const unique = (rows, key, name) => {
  const seen = new Set();
  for (const r of rows) {
    if (!r[key]) errors.push(`${name}: empty ${key}`);
    else if (seen.has(r[key])) errors.push(`${name}: duplicate ${key} ${r[key]}`);
    seen.add(r[key]);
  }
  return seen;
};
