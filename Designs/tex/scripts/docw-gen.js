// RFC 4180: quoted fields may hold commas, quotes ("") and line breaks; CRLF or LF.
function parseCsv(text, name) {
  text = text.replace(/^\uFEFF/, '');
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.some((f) => f !== '')) rows.push(row);
      row = [];
    } else field += c;
  }
  row.push(field);
  if (row.some((f) => f !== '')) rows.push(row);
  const head = rows.shift().map((h) => h.trim());
  return rows.map((r, n) => {
    if (r.length !== head.length) errors.push(`data/${name} row ${n + 2}: ${r.length} fields, header has ${head.length}`);
    return Object.fromEntries(head.map((h, k) => [h, (r[k] || '').trim()]));
  });
}
const load = (name) => parseCsv(fs.readFileSync(path.join(dataDir, name), 'utf8'), name);

// -------------------------------------------------------------- LaTeX ------
const tex = (s) => String(s)
  .replace(/\\/g, '\u0000').replace(/([&%$#_{}])/g, '\\$1')
  .replace(/~/g, '\\textasciitilde{}').replace(/\^/g, '\\textasciicircum{}')
  .replace(/\u0000/g, '\\textbackslash{}')
  .replace(/\\_/g, '\\_\\allowbreak{}')
  .replace(/ - /g, ' -- ');
// \dpath (main file) sets a path at table size; url ignores spaces, so a path with
// spaces is set as plain typewriter text with every space kept.
const fileTex = (p) => (/\s/.test(p) ? `\\texttt{\\scriptsize ${tex(p).replace(/ /g, '\\ ')}}` : `\\dpath{${p}}`);
const longtable = (cols, head, caption, label, body) => [
  `\\begin{longtable}[c]{@{}${cols.map((w) => `F{\\cw{${w}}{${(2 * (cols.length - 1) / cols.length).toFixed(4)}}}`).join('')}@{}}`,
  `\\caption{${caption}}\\label{${label}}\\\\`,
  '\\toprule', `${head.join(' & ')} \\\\`, '\\midrule', '\\endfirsthead',
  '\\toprule', `${head.join(' & ')} \\\\`, '\\midrule', '\\endhead',
  '\\bottomrule', '\\endlastfoot',
  ...body, '\\end{longtable}', ''].join('\n');
const groupRow = (n, title) => `\\multicolumn{${n}}{@{}l}{\\footnotesize\\bfseries ${tex(title)}} \\\\`;
// a group heading that may wrap across the full table width
const groupPar = (n, title) => `\\multicolumn{${n}}{@{}>{\\RaggedRight}p{\\linewidth}@{}}{\\footnotesize\\bfseries ${tex(title)}} \\\\`;
const write = (name, content) => fs.writeFileSync(path.join(outDir, name),
  `% generated by scripts/docw-gen.js from data/ -- do not edit\n${content}`.replace(/\n/g, '\r\n'));

