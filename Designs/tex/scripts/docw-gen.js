// consecutive spare points with nothing more to say are listed as one range
function collapse(rows) {
  const plain = (r) => r.signal === 'SPARE' && r.software === '--' && !r.notes && !r.use;
  const out = [];
  for (const r of rows) {
    const prev = out[out.length - 1];
    if (prev && plain(prev) && plain(r) && prev.far_end === r.far_end && +r.terminal === +prev.last.terminal + 1) prev.last = r;
    else out.push({ ...r, last: r });
  }
  const range = (a, b) => (a === b ? a : `${a}--${b.replace(/^.*[/ ]/, '')}`);
  return out.map((r) => ({ ...r, point: range(r.point, r.last.point), terminal: range(r.terminal, r.last.terminal),
    via: r.via && range(r.via, r.last.via) }));
}
