% accel_prm         - Accelerator parameters generator

function accel = accel_prm(machine)

switch (machine)
  case 'als'
    % alpha=1.37e-3 after the SuperBends according to C. Steyer 11/2/2001
    accel = struct(	'alpha', 1.6e-3, ...
			'Ebeam', 1.5e9, ...
			'wrf',   2*pi*500e6, ...
			'Io',    400, ...
			'Nbun',  272, ...
			'h',     328);
    accel.timestamp = '28-sep-2001';
  case 'dafne+'
    accel = struct(	'alpha', 0.026, ...
			'Ebeam', 510e6, ...
			'wrf',   2*pi*368e6, ...
			'Io',    200, ...
			'Nbun',  20, ...
			'h',     120);
    accel.timestamp = '16-apr-2000';
  case 'dafne-'
    accel = struct(	'alpha', 0.026, ...
			'Ebeam', 510e6, ...
			'wrf',   2*pi*368e6, ...
			'Io',    1000, ...
			'Nbun',  48, ...
			'h',     120);
    accel.timestamp = '21-nov-2000';
  case 'dafne1+'
    accel = struct(	'alpha', 0.029, ...
			'Ebeam', 510e6, ...
			'wrf',   2*pi*368e6, ...
			'Io',    1000, ...
			'Nbun',  100, ...
			'h',     120);
    accel.timestamp = '16-apr-2000';
  case 'dafne1-'
    accel = struct(	'alpha', 0.029, ...
			'Ebeam', 510e6, ...
			'wrf',   2*pi*368e6, ...
			'Io',    1000, ...
			'Nbun',  100, ...
			'h',     120);
    accel.timestamp = '21-nov-2000';
  % DAFNE with strong RF focusing: 10 MV gap voltage
  case 'dafne_strong'
    accel = struct(	'alpha', 0.171, ...
			'Ebeam', 510e6, ...
			'wrf',   2*pi*500e6, ...
			'Io',    1000, ...
			'Nbun',  140, ...
			'h',     175);
    accel.timestamp = '10-sep-2003';
  case 'bessy'
    accel = struct(	'alpha', 7.8e-4, ...
			'Ebeam', 1.7e9, ...
			'wrf',   2*pi*499.654e6, ...
			'Io',    250, ...
			'Nbun',  260, ...
			'h',     400);
    accel.timestamp = '6-aug-2004';
  case {'pepii-HER', 'pepii-HER-afs', 'pepii-LAB'}
    accel = struct(	'alpha', 0.00241, ...
			'Ebeam', 9e9, ...
			'wrf',   2*pi*476e6, ...
			'Io',    1500, ...
			'Nbun',  1616, ...
			'h',     3492);
    accel.timestamp = '6-aug-2004';
  case {'pepii-LER', 'pepii-LER-afs'}
    accel = struct(	'alpha', 0.00123, ...
			'Ebeam', 3.1e9, ...
			'wrf',   2*pi*476e6, ...
			'Io',    2500, ...
			'Nbun',  1616, ...
			'h',     3492);
    accel.timestamp = '26-jun-2003';
  case {'spear3'}
      % entered by jjs from CDR parameters
      % obtain current rf frequency
      % nominal value is 476.317e6
      fRfMHz = lcaGet( 'SPEAR:RFFreqSetpt' );
      fprintf(1, 'spear rf frequency = %9.5f MHz\n', fRfMHz );
    accel = struct(	'alpha', 0.00113, ...
			'Ebeam', 3.0e9, ...
			'wrf',   2*pi*fRfMHz*1e6, ...
			'Io',    100, ...
			'Nbun',  279, ...
			'h',     372);
    accel.timestamp = '03-dec-2003';
  otherwise
    accel.error = ['Unknown machine: ', machine];
    return;
end
